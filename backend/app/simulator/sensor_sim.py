"""
Nagpur WaterWatch — Sensor Simulator
======================================
Simulates ESP32/Arduino sensor readings for demonstration.
Generates changing water levels and rainfall scenarios.

All data generated by this simulator is clearly marked as
DEMO / SIMULATED DATA.

Usage:
    python -m app.simulator.sensor_sim
    python -m app.simulator.sensor_sim --interval 10 --scenario heavy_rain
"""

import argparse
import random
import time
from datetime import datetime
from sqlalchemy.orm import Session
from app.database import SessionLocal, engine, Base
from app.models.sensor import Sensor, SensorReading, SensorStatus
from app.models.weather import RainfallObservation


# ──────────── Rainfall Scenarios ────────────
SCENARIOS = {
    "dry": {
        "rainfall_range": (0, 2),
        "water_level_change": (-2, 1),
        "description": "Dry weather — minimal water accumulation",
    },
    "light_rain": {
        "rainfall_range": (2, 10),
        "water_level_change": (-1, 5),
        "description": "Light rain — slow water level increase",
    },
    "moderate_rain": {
        "rainfall_range": (10, 30),
        "water_level_change": (2, 15),
        "description": "Moderate rain — noticeable waterlogging in low areas",
    },
    "heavy_rain": {
        "rainfall_range": (30, 65),
        "water_level_change": (5, 30),
        "description": "Heavy rain — significant waterlogging expected",
    },
    "extreme": {
        "rainfall_range": (65, 120),
        "water_level_change": (15, 50),
        "description": "Extreme rainfall — severe flooding conditions",
    },
    "clearing": {
        "rainfall_range": (0, 5),
        "water_level_change": (-10, -2),
        "description": "Rain stopping — water levels receding",
    },
}


def simulate_readings(scenario_name: str = "moderate_rain", interval: int = 15):
    """
    Run the sensor simulator continuously.

    Args:
        scenario_name: One of the predefined rainfall scenarios
        interval: Seconds between readings
    """
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()

    scenario = SCENARIOS.get(scenario_name, SCENARIOS["moderate_rain"])
    print(f"\n{'='*60}")
    print(f"  NAGPUR WATERWATCH — SENSOR SIMULATOR")
    print(f"  ⚠  ALL DATA IS DEMO / SIMULATED")
    print(f"{'='*60}")
    print(f"  Scenario: {scenario_name}")
    print(f"  Description: {scenario['description']}")
    print(f"  Interval: {interval}s")
    print(f"{'='*60}\n")

    sensors = db.query(Sensor).filter(Sensor.is_simulated == True).all()
    if not sensors:
        print("No simulated sensors found. Run seed_data.py first.")
        return

    print(f"Found {len(sensors)} simulated sensors.\n")

    # Track current water levels per sensor
    water_levels = {}
    for s in sensors:
        water_levels[s.sensor_id] = random.uniform(0, 10)

    iteration = 0
    try:
        while True:
            iteration += 1
            now = datetime.utcnow()
            rainfall = round(random.uniform(*scenario["rainfall_range"]), 1)

            print(f"── Iteration {iteration} | {now.strftime('%H:%M:%S')} | Rainfall: {rainfall} mm ──")

            # Store weather observation
            obs = RainfallObservation(
                rainfall_mm=rainfall,
                intensity="heavy" if rainfall >= 30 else "moderate" if rainfall >= 10 else "light" if rainfall > 0 else "none",
                humidity=round(random.uniform(70, 95), 1),
                temperature_c=round(random.uniform(24, 30), 1),
                weather_condition=scenario["description"],
                data_source="simulated",
                is_simulated=True,
                observed_at=now,
            )
            db.add(obs)

            for sensor in sensors:
                # Simulate water level change
                change = random.uniform(*scenario["water_level_change"])
                # Add some per-sensor variation based on drainage
                variation = random.uniform(-3, 3)
                new_level = max(0, water_levels[sensor.sensor_id] + change + variation)
                new_level = min(new_level, 100)  # cap at 100cm
                water_levels[sensor.sensor_id] = new_level

                # Simulate battery drain
                battery = max(0, sensor.battery_level - random.uniform(0, 0.1))

                reading = SensorReading(
                    sensor_db_id=sensor.id,
                    sensor_id=sensor.sensor_id,
                    water_level=round(new_level, 1),
                    battery_level=round(battery, 1),
                    is_simulated=True,
                    timestamp=now,
                )
                db.add(reading)

                sensor.last_reading_at = now
                sensor.battery_level = round(battery, 1)
                sensor.status = SensorStatus.ONLINE

                severity = "🔴" if new_level >= 30 else "🟠" if new_level >= 15 else "🟡" if new_level >= 5 else "🟢"
                print(f"  {severity} {sensor.sensor_id} ({sensor.location_name[:25]:25s}): {new_level:5.1f} cm | Battery: {battery:.0f}%")

            db.commit()
            print()
            time.sleep(interval)

    except KeyboardInterrupt:
        print("\nSimulator stopped.")
    finally:
        db.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Nagpur WaterWatch Sensor Simulator")
    parser.add_argument(
        "--scenario", "-s",
        choices=list(SCENARIOS.keys()),
        default="moderate_rain",
        help="Rainfall scenario to simulate",
    )
    parser.add_argument(
        "--interval", "-i",
        type=int,
        default=15,
        help="Seconds between readings (default: 15)",
    )
    args = parser.parse_args()
    simulate_readings(scenario_name=args.scenario, interval=args.interval)
